export function normalizeLanguageCode(value?: string): LanguageCode {
  const normalized = (value || "en").toLowerCase().replace("_", "-");
  const base = normalized.split("-")[0] as LanguageCode;
  return supportedLanguages.some((language) => language.code === base) ? base : "en";
}

export function languageDirection(language: LanguageCode) {
  return language === "ar" ? "rtl" : "ltr";
}

export function translate(language: LanguageCode, key: TranslationKey, values: TranslationValues = {}) {
  const template = dictionaries[language][key] ?? english[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}
